#!/usr/bin/env node
// Writes src/schema.snapshot.ts from the API's OpenAPI document: the response types as TypeScript (what code
// written in `execute` is type-checked against) and, per operation, the type it returns.
//
//   node scripts/gen-schema.mjs <openapi.json>      (tools/public/generate-sdks.sh passes apps/web/public/openapi.json)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("usage: gen-schema.mjs <openapi.json>");
  process.exit(2);
}
const doc = JSON.parse(readFileSync(input, "utf8"));
const schemas = doc.components?.schemas ?? {};

const refName = (ref) => ref.replace("#/components/schemas/", "");
const isWrapper = (name) => /Response$/.test(name) && schemas[name]?.properties?.data;
const ident = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

function ts(s, indent) {
  if (!s || Object.keys(s).length === 0) return "unknown";
  if (s.$ref) return refName(s.$ref);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.anyOf || s.oneOf) return [...new Set((s.anyOf ?? s.oneOf).map((x) => ts(x, indent)))].join(" | ");
  if (s.allOf) return s.allOf.map((x) => ts(x, indent)).join(" & ");
  const type = Array.isArray(s.type) ? s.type : [s.type];
  const parts = type.map((t) => {
    switch (t) {
      case "string": return "string";
      case "integer":
      case "number": return "number";
      case "boolean": return "boolean";
      case "null": return "null";
      case "array": return `${wrap(ts(s.items, indent))}[]`;
      case "object": return object(s, indent);
      default: return s.properties ? object(s, indent) : "unknown";
    }
  });
  return parts.join(" | ");
}
const wrap = (t) => (/[|&]/.test(t) ? `(${t})` : t);

function object(s, indent) {
  const props = s.properties ?? {};
  const keys = Object.keys(props);
  if (!keys.length) return "Record<string, unknown>";
  const req = new Set(s.required ?? []);
  const pad = "  ".repeat(indent + 1);
  const lines = keys.map((k) => {
    const p = props[k];
    const doc = p.description ? `${pad}/** ${p.description.replace(/\*\//g, "* /").replace(/\s+/g, " ").slice(0, 160)} */\n` : "";
    return `${doc}${pad}${ident(k)}${req.has(k) ? "" : "?"}: ${ts(p, indent + 1)};`;
  });
  return `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}`;
}

const types = Object.keys(schemas)
  .filter((n) => !isWrapper(n) && n !== "ErrorResponse")
  .sort()
  .map((n) => {
    const s = schemas[n];
    const body = ts(s, 0);
    const doc = s.description ? `/** ${s.description.replace(/\s+/g, " ").slice(0, 200)} */\n` : "";
    return body.startsWith("{") ? `${doc}interface ${n} ${body}` : `${doc}type ${n} = ${body};`;
  })
  .join("\n");

// "platform/operation" → the type its `data` holds, from each path's 200 response.
const returns = {};
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  const m = path.match(/^\/v1\/([^/]+)\/([^/]+)$/);
  if (!m) continue;
  for (const op of Object.values(item)) {
    const ref = op?.responses?.["200"]?.content?.["application/json"]?.schema?.$ref;
    if (!ref) continue;
    const wrapper = schemas[refName(ref)];
    const data = wrapper?.properties?.data;
    returns[`${m[1]}/${m[2]}`] = data?.$ref ? refName(data.$ref) : ts(data ?? {}, 0);
  }
}

const out =
  "// GENERATED by scripts/gen-schema.mjs from the OpenAPI document (tools/public/generate-sdks.sh). Do not edit.\n" +
  "// The response types code in `execute` is checked against, and the type each operation returns.\n" +
  `export const SCHEMA_TYPES: string = ${JSON.stringify(types)};\n` +
  `export const RETURNS: Record<string, string> = ${JSON.stringify(returns, null, 1)};\n`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "..", "src", "schema.snapshot.ts"), out);
console.log(`gen-schema: ${Object.keys(schemas).length} schemas, ${Object.keys(returns).length} operations`);
